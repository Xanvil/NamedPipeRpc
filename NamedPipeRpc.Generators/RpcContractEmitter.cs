using System.Collections.Immutable;
using System.Text;

namespace Xanvil.NamedPipeRpc.Generators;

/// <summary>
/// 生成契约代理，以及 HandlerRouter / NamedPipePeer 上的 Handler、Proxy 扩展。
/// </summary>
internal static class RpcContractEmitter
{
    /// <summary>为接口契约生成实现该接口的代理类，以及业务参数的 Args 参数包。</summary>
    public static string EmitInterfaceProxy(ContractTypeModel contract)
    {
        string proxyName = contract.ProxyTypeName
            ?? throw new InvalidOperationException("接口契约缺少 ProxyTypeName。");

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using Xanvil.NamedPipeRpc;");
        sb.AppendLine();
        EmitNamespaceOpen(sb, contract.ContainingNamespace);
        EmitArgsTypes(sb, contract, GetTypeIndent(contract.ContainingNamespace));

        string ind = GetTypeIndent(contract.ContainingNamespace);
        string via = contract.Role == ContractRole.Notify ? "Notify" : "Request";
        sb.AppendLine($"{ind}/// <summary>由 Source Generator 生成的 <see cref=\"{contract.TypeDisplay}\"/> 出站代理，调用转发为这条连接上的 Peer.{via}。</summary>");
        sb.AppendLine($"{ind}[CompilerGenerated]");
        sb.AppendLine($"{ind}{contract.Accessibility} sealed class {proxyName} : {contract.TypeDisplay}");
        sb.AppendLine($"{ind}{{");
        sb.AppendLine($"{ind}    readonly NamedPipePeer _peer;");
        sb.AppendLine();
        sb.AppendLine($"{ind}    /// <summary>绑定一条连接。后续调用只发到这条连接。</summary>");
        sb.AppendLine($"{ind}    public {proxyName}(NamedPipePeer peer)");
        sb.AppendLine($"{ind}    {{");
        sb.AppendLine($"{ind}        _peer = peer ?? throw new ArgumentNullException(nameof(peer));");
        sb.AppendLine($"{ind}    }}");
        sb.AppendLine();

        foreach (var method in contract.Methods)
            EmitProxyMethod(sb, contract, method, ind + "    ");

        sb.AppendLine($"{ind}}}");
        EmitNamespaceClose(sb, contract.ContainingNamespace);
        return sb.ToString();
    }

    /// <summary>类契约只生成多参 Args。没有两个及以上业务参数的方法时不生成文件。</summary>
    public static string EmitClassArgsOnly(ContractTypeModel contract)
    {
        if (contract.Methods.All(m => m.ArgsTypeName is null))
            return string.Empty;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        EmitNamespaceOpen(sb, contract.ContainingNamespace);
        EmitArgsTypes(sb, contract, GetTypeIndent(contract.ContainingNamespace));
        EmitNamespaceClose(sb, contract.ContainingNamespace);
        return sb.ToString();
    }

    /// <summary>生成 Add/Get Handler 与 Proxy 扩展。</summary>
    public static string EmitExtensions(ImmutableArray<ContractTypeModel> contracts)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using Xanvil.NamedPipeRpc;");
        sb.AppendLine();
        sb.AppendLine("namespace Xanvil.NamedPipeRpc");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>由 Source Generator 生成的契约注册与代理获取。</summary>");
        sb.AppendLine("    public static class RpcGeneratedExtensions");
        sb.AppendLine("    {");

        EmitAddHandler(sb, contracts, ContractRole.Request);
        EmitGetProxy(sb, contracts, ContractRole.Request);

        EmitAddHandler(sb, contracts, ContractRole.Notify);
        EmitAddNotifyProxy(sb, contracts);
        EmitGetProxy(sb, contracts, ContractRole.Notify);

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    static void EmitAddHandler(
        StringBuilder sb,
        ImmutableArray<ContractTypeModel> contracts,
        ContractRole role)
    {
        string method = role == ContractRole.Request ? "AddRequestHandler" : "AddNotifyHandler";
        string summary = role == ContractRole.Request
            ? "登记请求服务工厂。方法名立即进入目录；每条连接 Start 时创建一个实例。"
            : "登记本端可以接收的通知工厂。每条连接一个实例，不会因此自动订阅。";
        sb.AppendLine("        /// <summary>" + summary + "</summary>");
        sb.AppendLine($"        public static void {method}<TContract>(this HandlerRouter router, Func<NamedPipePeer, TContract> factory)");
        sb.AppendLine("            where TContract : class");
        sb.AppendLine("        {");
        sb.AppendLine("            if (router is null) throw new ArgumentNullException(nameof(router));");
        sb.AppendLine("            if (factory is null) throw new ArgumentNullException(nameof(factory));");
        sb.AppendLine("            bool matched = false;");

        foreach (var c in contracts)
        {
            if (c.Role != role)
                continue;
            // 工厂的返回类型是契约，或是实现了该契约的类。其它程序集里的实现类也能对上。
            sb.AppendLine($"            if (typeof({c.TypeDisplay}).IsAssignableFrom(typeof(TContract)))");
            sb.AppendLine("            {");
            sb.AppendLine($"                router.ReserveConnectionContract(typeof({c.TypeDisplay}));");
            sb.AppendLine($"                Register_{c.HintName}(router);");
            sb.AppendLine("                matched = true;");
            sb.AppendLine("            }");
        }

        string kind = role == ContractRole.Request ? "RpcRequest" : "RpcNotify";
        sb.AppendLine("            if (!matched)");
        sb.AppendLine("                throw new InvalidOperationException(");
        sb.AppendLine($"                    \"未找到类型 \" + typeof(TContract).FullName + \" 的 {method}。请确认已标注 [{kind}]。\");");
        sb.AppendLine("            router.AddConnectionFactory(peer =>");
        sb.AppendLine("            {");
        sb.AppendLine("                TContract created = factory(peer);");
        sb.AppendLine("                if (created is null) throw new InvalidOperationException(\"处理器工厂返回了 null。\");");
        sb.AppendLine("                if (created.GetType().IsDefined(typeof(CompilerGeneratedAttribute), false))");
        sb.AppendLine("                    throw new InvalidOperationException(\"代理对象不能作为 Handler 注册。\");");
        sb.AppendLine("                bool stored = false;");
        foreach (var c in contracts)
        {
            if (c.Role != role)
                continue;
            sb.AppendLine($"                if (created is {c.TypeDisplay} {c.HintName.ToLowerInvariant()}Value)");
            sb.AppendLine($"                    stored |= peer.TryAddConnectionHandler(typeof({c.TypeDisplay}), {c.HintName.ToLowerInvariant()}Value);");
        }
        sb.AppendLine("                if (!stored && created is IDisposable extra)");
        sb.AppendLine("                    extra.Dispose();");
        sb.AppendLine("            });");
        sb.AppendLine("        }");
        sb.AppendLine();

        foreach (var c in contracts)
        {
            if (c.Role == role)
                EmitRegisterHelper(sb, c);
        }
    }

    /// <summary>登记连接后要自动订阅的通知契约。</summary>
    static void EmitAddNotifyProxy(StringBuilder sb, ImmutableArray<ContractTypeModel> contracts)
    {
        sb.AppendLine("        /// <summary>连接建立后自动订阅该通知契约。接收处理仍由 AddNotifyHandler 登记。</summary>");
        sb.AppendLine("        public static void AddNotifyProxy<TContract>(this HandlerRouter router)");
        sb.AppendLine("            where TContract : class");
        sb.AppendLine("        {");
        sb.AppendLine("            if (router is null) throw new ArgumentNullException(nameof(router));");
        sb.AppendLine("            var t = typeof(TContract);");

        foreach (var c in contracts)
        {
            if (c.Role != ContractRole.Notify || c.Kind != ContractKind.Interface)
                continue;
            sb.AppendLine($"            if (t == typeof({c.TypeDisplay}))");
            sb.AppendLine("            {");
            foreach (var m in c.Methods)
            {
                string rpc = ToCSharpStringLiteral(m.RpcName);
                sb.AppendLine($"                router.UseNotifyAutoSubscribe({rpc});");
            }
            sb.AppendLine("                return;");
            sb.AppendLine("            }");
        }

        sb.AppendLine("            throw new InvalidOperationException(");
        sb.AppendLine("                \"未找到类型 \" + t.FullName + \" 的 AddNotifyProxy。请确认接口已标注 [RpcNotify]。\");");
        sb.AppendLine("        }");
        sb.AppendLine();
    }

    /// <summary>在一条连接上取出并缓存出站代理。</summary>
    static void EmitGetProxy(
        StringBuilder sb,
        ImmutableArray<ContractTypeModel> contracts,
        ContractRole role)
    {
        string method = role == ContractRole.Request ? "GetRequestProxy" : "GetNotifyProxy";
        bool notify = role == ContractRole.Notify;
        string flag = notify ? "true" : "false";
        string kind = notify ? "RpcNotify" : "RpcRequest";

        sb.AppendLine(notify
            ? "        /// <summary>返回源生成器生成的通知代理，只向这一条连接发送。静态类型是契约接口。</summary>"
            : "        /// <summary>返回源生成器生成的请求代理，只向这一条连接发送。静态类型是契约接口。同一契约在这条连接上只创建一次。</summary>");
        sb.AppendLine($"        public static TContract {method}<TContract>(this NamedPipePeer peer)");
        sb.AppendLine("            where TContract : class");
        sb.AppendLine("        {");
        sb.AppendLine("            if (peer is null) throw new ArgumentNullException(nameof(peer));");
        sb.AppendLine("            var t = typeof(TContract);");
        sb.AppendLine($"            if (peer.TryGetContractProxy(t, {flag}, out var cached) && cached is not null)");
        sb.AppendLine("                return (TContract)cached;");

        foreach (var c in contracts)
        {
            if (c.Role != role || c.Kind != ContractKind.Interface)
                continue;
            string proxyFq = QualifyType(c.ContainingNamespace, c.ProxyTypeName!);
            sb.AppendLine($"            if (t == typeof({c.TypeDisplay}))");
            sb.AppendLine("            {");
            sb.AppendLine($"                var created = new {proxyFq}(peer);");
            sb.AppendLine($"                peer.AddContractProxy(t, created, {flag});");
            sb.AppendLine("                return (TContract)(object)created;");
            sb.AppendLine("            }");
        }

        sb.AppendLine("            throw new InvalidOperationException(");
        sb.AppendLine($"                \"未找到类型 \" + t.FullName + \" 的 {method}。请确认接口已标注 [{kind}]。\");");
        sb.AppendLine("        }");
        sb.AppendLine();
    }

    static void EmitRegisterHelper(StringBuilder sb, ContractTypeModel contract)
    {
        sb.AppendLine($"        static void Register_{contract.HintName}(HandlerRouter router)");
        sb.AppendLine("        {");
        foreach (var method in contract.Methods)
        {
            string reqType = GetRequestTypeDisplay(contract, method);
            string rpc = ToCSharpStringLiteral(method.RpcName);
            string invoke = BuildHandlerInvokeExpression(contract, method);
            if (contract.Role == ContractRole.Notify)
            {
                sb.AppendLine($"            router.AddNotifyHandler<{reqType}>({rpc}, (ctx, ct) => {invoke});");
                sb.AppendLine($"            router.KeepNotifyLocal({rpc});");
            }
            else if (method.ResponseTypeDisplay is null)
            {
                sb.AppendLine($"            router.AddRequestHandler<{reqType}, Unit>({rpc}, async (ctx, ct) =>");
                sb.AppendLine("            {");
                sb.AppendLine($"                await {invoke};");
                sb.AppendLine("                return Unit.Value;");
                sb.AppendLine("            });");
            }
            else
            {
                sb.AppendLine($"            router.AddRequestHandler<{reqType}, {method.ResponseTypeDisplay}>({rpc}, (ctx, ct) => {invoke});");
            }
        }
        sb.AppendLine("        }");
        sb.AppendLine();
    }

    static void EmitProxyMethod(StringBuilder sb, ContractTypeModel contract, ContractMethodModel method, string ind)
    {
        string paramList = BuildParameterList(method);
        string ctArg = method.HasCancellationToken ? method.CancellationTokenParameterName! : "default";
        string returnType = contract.Role == ContractRole.Notify || method.ResponseTypeDisplay is null
            ? "Task"
            : $"Task<{method.ResponseTypeDisplay}>";
        sb.AppendLine($"{ind}public {returnType} {method.MethodName}({paramList})");
        sb.AppendLine($"{ind}{{");
        string reqExpr = BuildPayloadExpression(contract, method);
        string reqType = GetRequestTypeDisplay(contract, method);
        string rpc = ToCSharpStringLiteral(method.RpcName);
        if (contract.Role == ContractRole.Notify)
        {
            if (method.Parameters.Length == 0)
                sb.AppendLine($"{ind}    return _peer.Notify({rpc}, {ctArg});");
            else
                sb.AppendLine($"{ind}    return _peer.Notify<{reqType}>({rpc}, {reqExpr}, {ctArg});");
        }
        else if (method.ResponseTypeDisplay is null)
        {
            if (method.Parameters.Length == 0)
                sb.AppendLine($"{ind}    return _peer.Request({rpc}, {ctArg});");
            else
                sb.AppendLine($"{ind}    return _peer.Request<{reqType}, Unit>({rpc}, {reqExpr}, {ctArg});");
        }
        else if (method.Parameters.Length == 0)
        {
            sb.AppendLine($"{ind}    return _peer.Request<Unit, {method.ResponseTypeDisplay}>({rpc}, Unit.Value, {ctArg});");
        }
        else
        {
            sb.AppendLine($"{ind}    return _peer.Request<{reqType}, {method.ResponseTypeDisplay}>({rpc}, {reqExpr}, {ctArg});");
        }
        sb.AppendLine($"{ind}}}");
        sb.AppendLine();
    }

    static void EmitArgsTypes(StringBuilder sb, ContractTypeModel contract, string indent)
    {
        foreach (var method in contract.Methods)
        {
            if (method.ArgsTypeName is null)
                continue;
            sb.AppendLine($"{indent}/// <summary>");
            sb.AppendLine($"{indent}/// {contract.TypeFullName}.{method.MethodName} 的多参载荷包。");
            sb.AppendLine($"{indent}/// 只有两个及以上业务参数才生成。字段名等于参数名。");
            sb.AppendLine($"{indent}/// 缺少的字段使用该类型的默认值。单个参数不使用此类型。");
            sb.AppendLine($"{indent}/// </summary>");
            sb.AppendLine($"{indent}{contract.Accessibility} struct {method.ArgsTypeName}");
            sb.AppendLine($"{indent}{{");
            foreach (var p in method.Parameters)
            {
                sb.AppendLine($"{indent}    /// <summary>参数 {EscapeIdentifier(p.Name)}。JSON 中缺少时使用该类型的默认值。</summary>");
                sb.AppendLine($"{indent}    public {p.TypeDisplay} {EscapeIdentifier(p.Name)};");
            }
            sb.AppendLine($"{indent}}}");
            sb.AppendLine();
        }
    }

    static string BuildParameterList(ContractMethodModel method)
    {
        string ctParam = method.HasCancellationToken
            ? $", CancellationToken {method.CancellationTokenParameterName!} = default"
            : "";
        string paramList = string.Join(", ", method.Parameters.Select(p => $"{p.TypeDisplay} {EscapeIdentifier(p.Name)}"));
        if (paramList.Length > 0 && method.HasCancellationToken)
            paramList += ctParam;
        else if (method.HasCancellationToken)
            paramList = ctParam.TrimStart(',', ' ');
        return paramList;
    }

    static string BuildHandlerInvokeExpression(ContractTypeModel contract, ContractMethodModel method)
    {
        string receiver = $"ctx.Peer.GetConnectionHandler<{contract.TypeDisplay}>()";
        string ctArg = method.HasCancellationToken ? "ct" : "";
        if (method.Parameters.Length == 0)
            return method.HasCancellationToken ? $"{receiver}.{method.MethodName}({ctArg})" : $"{receiver}.{method.MethodName}()";
        if (method.Parameters.Length == 1)
            return method.HasCancellationToken
                ? $"{receiver}.{method.MethodName}(ctx.Message, {ctArg})"
                : $"{receiver}.{method.MethodName}(ctx.Message)";
        string joined = string.Join(", ", method.Parameters.Select(p => $"ctx.Message.{EscapeIdentifier(p.Name)}"));
        return method.HasCancellationToken
            ? $"{receiver}.{method.MethodName}({joined}, {ctArg})"
            : $"{receiver}.{method.MethodName}({joined})";
    }

    static string BuildPayloadExpression(ContractTypeModel contract, ContractMethodModel method)
    {
        if (method.Parameters.Length == 0)
            return "Unit.Value";
        if (method.Parameters.Length == 1)
            return EscapeIdentifier(method.Parameters[0].Name);
        string argsType = GetRequestTypeDisplay(contract, method);
        string inits = string.Join(", ", method.Parameters.Select(p => $"{EscapeIdentifier(p.Name)} = {EscapeIdentifier(p.Name)}"));
        return $"new {argsType} {{ {inits} }}";
    }

    static string GetRequestTypeDisplay(ContractTypeModel contract, ContractMethodModel method)
    {
        if (method.Parameters.Length == 0)
            return "Unit";
        if (method.Parameters.Length == 1)
            return method.Parameters[0].TypeDisplay;
        return QualifyType(contract.ContainingNamespace, method.ArgsTypeName!);
    }

    static string QualifyType(string containingNamespace, string typeName)
    {
        if (string.IsNullOrEmpty(containingNamespace))
            return "global::" + typeName;
        return "global::" + containingNamespace + "." + typeName;
    }

    static void EmitNamespaceOpen(StringBuilder sb, string containingNamespace)
    {
        if (string.IsNullOrEmpty(containingNamespace))
            return;
        sb.AppendLine($"namespace {containingNamespace}");
        sb.AppendLine("{");
    }

    static void EmitNamespaceClose(StringBuilder sb, string containingNamespace)
    {
        if (string.IsNullOrEmpty(containingNamespace))
            return;
        sb.AppendLine("}");
    }

    static string GetTypeIndent(string containingNamespace)
        => string.IsNullOrEmpty(containingNamespace) ? "" : "    ";

    static string ToCSharpStringLiteral(string value)
        => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    static string EscapeIdentifier(string name)
    {
        switch (name)
        {
            case "event":
            case "class":
            case "namespace":
            case "object":
            case "string":
            case "int":
            case "params":
            case "base":
            case "this":
            case "default":
            case "new":
                return "@" + name;
            default:
                return name;
        }
    }
}
